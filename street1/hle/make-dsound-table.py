"""Build the DirectSound HLE table: every named DSOUND function the generated
game code (outside the DSOUND section) calls.

Inputs : hle/xbsdb_symbols.txt, project/src/recomp/gen/*.c
Outputs: hle/dsound_functions.json
         project/src/hle_dsound_table.h -- HLE_DS(va, name, conv, args) X-macro
"""
from pathlib import Path
import collections
import json
import re

here = Path(__file__).resolve().parent
gen = here.parent / 'project/src/recomp/gen'
DS_LO, DS_HI = 0x265E20, 0x26F240

sym = {}
for line in (here / 'xbsdb_symbols.txt').read_text().splitlines():
    m = re.match(r'(\w+?)__FUN__(\w+?)__(\w+)\((.*)\) = 0x([0-9a-f]+)$', line.strip())
    if not m:
        continue
    lib, conv, name, params, va = m.groups()
    args = [p.strip().split() for p in params.split(',') if p.strip()]
    sym[int(va, 16)] = dict(lib=lib, conv=conv, name=name,
                            args=[{'loc': a[0], 'name': a[1]} for a in args])

func_re = re.compile(r'^void sub_([0-9A-F]{8})(?:_gen)?\(void\)')
call_re = re.compile(r'RECOMP_ABI_CALL\(0x([0-9A-F]{8})u')
sites = collections.Counter()
for path in sorted(gen.glob('recomp_00*.c')):
    cur = None
    for line in path.read_text(encoding='utf-8', errors='ignore').splitlines():
        m = func_re.match(line)
        if m:
            cur = int(m.group(1), 16)
            continue
        for t in call_re.findall(line):
            t = int(t, 16)
            if DS_LO <= t < DS_HI and cur is not None and not (DS_LO <= cur < DS_HI):
                sites[t] += 1

table, unnamed = {}, []
for va, n in sorted(sites.items()):
    s = sym.get(va)
    if not s:
        unnamed.append(f'{va:08X}')
        continue
    table[f'{va:08X}'] = dict(s, sites=n)

(here / 'dsound_functions.json').write_text(json.dumps(table, indent=1))
lines = ['/* Generated by street1/hle/make-dsound-table.py -- do not edit. */',
         '/* HLE_DS(va8, name, conv, stack_args) */']
for va_hex in sorted(table):
    t = table[va_hex]
    stack = sum(1 for a in t['args'] if a['loc'] == 'psh') + \
            sum(2 for a in t['args'] if a['loc'] == 'psh2')
    lines.append(f"HLE_DS({va_hex}, {t['name']}, {t['conv']}, {stack})")
(here.parent / 'project/src/hle_dsound_table.h').write_text('\n'.join(lines) + '\n')
print(f'DSOUND table: {len(table)} named, unnamed: {unnamed}')
