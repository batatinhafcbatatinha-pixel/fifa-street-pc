"""Generate hle/smp_serial_functions.json + project/src/hle_smp_serial.c.

Under RECOMP_GUEST_SMP the title's own heap code (EA allocator, which takes
its critical section only for heaps flagged thread-safe, and the MemoryX
tracking layer above it) runs under the guest kernel lock, as it ran under
the single CPU on the console.
"""
from pathlib import Path
import json, re, sys

street1 = Path(sys.argv[1])
gen = street1 / 'project/src/recomp/gen'
ranges = [
    (0x0016198D, 0x001627F4, 'EA heap allocator'),
    (0x00227CB4, 0x002285F0, 'MemoryX allocation layer'),
    (0x002372F0, 0x0023AD00, 'EA stream/packet library (movies, audio streams)'),
]
addrs = set()
for f in gen.glob('recomp_00*.c'):
    for m in re.finditer(r'^void sub_([0-9A-F]{8})(?:_gen)?\(void\)', f.read_text(encoding='utf-8', errors='replace'), re.M):
        a = int(m.group(1), 16)
        for lo, hi, _ in ranges:
            if lo <= a <= hi:
                addrs.add(a)
addrs = sorted(addrs)
table = {f'{a:08X}': {'lib': 'GAME', 'conv': 'any', 'name': f'smp_serial_{a:08X}',
                      'native': 'project/src/hle_smp_serial.c'} for a in addrs}
(street1 / 'hle/smp_serial_functions.json').write_text(json.dumps(table, indent=1) + '\n', encoding='utf-8')

out = ['/*',
       ' * Generated by hle/make-smp-serial.py.',
       ' *',
       ' * RECOMP_GUEST_SMP: title code written for the console\'s single CPU runs',
       ' * under the guest kernel lock, as it ran on that CPU:',
       ' *  - EA\'s heap allocator takes its own critical section only for heaps',
       ' *    created thread-safe, and the MemoryX tracking layer above it;',
       ' *  - EA\'s stream/packet library (movies, audio streams): with threads in',
       ' *    parallel the main thread read a channel whose ring still held the',
       ' *    0xBB55BB55 new-block fill (crash at the first movie, 4 boots in 5).',
       ' * Without SMP guest_cpu_native_enter() is a no-op.',
       ' */',
       '#include "recomp/gen/recomp_types.h"',
       '',
       'int guest_cpu_native_enter(void);',
       'void guest_cpu_native_leave(int token);',
       '']
for a in addrs:
    out.append(f'void sub_{a:08X}_gen(void);')
out.append('')
for a in addrs:
    out.append(f'void sub_{a:08X}(void) {{ int s = guest_cpu_native_enter(); sub_{a:08X}_gen(); guest_cpu_native_leave(s); }}')
(street1 / 'project/src/hle_smp_serial.c').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
print(len(addrs), 'functions')
