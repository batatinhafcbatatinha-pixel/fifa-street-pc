"""Build the HLE function table from XbSymbolDatabase output and real usage.

Inputs : hle/xbsdb_symbols.txt (XbSymbolDatabaseCLI default.xbe -e)
         hle/d3d_api_usage.json (D3D functions the generated game code calls)
Outputs: hle/hle_functions.json
         project/src/hle_d3d8_table.h  -- HLE_API(va, name, conv, args) X-macro
Only named functions are routed; unnamed ones are reported and left generated.
"""
from pathlib import Path
import json
import re

here = Path(__file__).resolve().parent
usage = json.loads((here / 'd3d_api_usage.json').read_text())
sym = {}
for line in (here / 'xbsdb_symbols.txt').read_text().splitlines():
    m = re.match(r'(\w+?)__FUN__(\w+?)__(\w+)\((.*)\) = 0x([0-9a-f]+)$', line.strip())
    if not m:
        continue
    lib, conv, name, params, va = m.groups()
    args = [p.strip().split() for p in params.split(',') if p.strip()]
    sym[int(va, 16)] = dict(lib=lib, conv=conv, name=name,
                            args=[{'loc': a[0], 'name': a[1]} for a in args])

# Library functions the game calls that XbSymbolDatabase leaves unnamed; names
# and stack arguments from their bodies (ret N) and the D3D8 5849 API.
def _psh(*names):
    return [{'loc': 'psh', 'name': n} for n in names]
EXTRA = {
    0x25A860: dict(lib='D3D8', conv='stdcall', name='D3DDevice_CreateImageSurface',
                   args=_psh('Width', 'Height', 'Usage', 'Format')),
    0x25CEA0: dict(lib='D3D8', conv='stdcall', name='D3DDevice_End', args=[]),
    0x25CF30: dict(lib='D3D8', conv='stdcall', name='D3D_FreeContiguousMemory',
                   args=_psh('pMemory')),
    0x25D000: dict(lib='D3D8', conv='stdcall', name='D3DTexture_GetLevelDesc',
                   args=_psh('pThis', 'Level', 'pDesc')),
    0x25E390: dict(lib='D3D8', conv='stdcall', name='D3D_ReturnTrue_25E390',
                   args=_psh('Unused')),
}
for va, s in EXTRA.items():
    sym.setdefault(va, s)
for va_hex in ('0025CEA0',):
    usage.setdefault(va_hex, {'name': EXTRA[int(va_hex, 16)]['name'], 'sites': 2})

table, unnamed = {}, []
for va_hex, u in usage.items():
    va = int(va_hex, 16)
    s = sym.get(va)
    if not s:
        unnamed.append(va_hex)
        continue
    table[f'{va:08X}'] = dict(s, sites=u['sites'])

(here / 'hle_functions.json').write_text(json.dumps(table, indent=1))
lines = ['/* Generated by street1/hle/make-hle-table.py -- do not edit. */',
         '/* HLE_API(va8, name, conv, stack_args): va8 = 8 hex digits, sub_##va8 */']
for va_hex in sorted(table):
    t = table[va_hex]
    stack = sum(1 for a in t['args'] if a['loc'] == 'psh')
    lines.append(f"HLE_API({va_hex}, {t['name']}, {t['conv']}, {stack})")
(here.parent / 'project/src/hle_d3d8_table.h').write_text('\n'.join(lines) + '\n')
print(f'HLE table: {len(table)} named, unnamed (left generated): {unnamed}')
