"""Add game functions the original disassembly never found to the generated code.

They are reached only through function pointers that static initializers build
in code (mov eax, imm32 / mov [table], eax) or through one data vtable slot, so
the full-program detector missed them and every call was skipped with
"[ICALL] Failed to resolve VA". Regenerating all 55 units would drop the scoped
post-passes applied since, so instead each missing function is translated alone
(tools.recomp -f, same generator and disassembly plus these seeds) into
gen/recomp_extra.c, declared in recomp_funcs.h and inserted into the sorted
dispatch table. Idempotent.

usage: add-missing-functions.py <disasm dir> <func_id dir> <abi dir>
"""
from pathlib import Path
import re
import subprocess
import sys

MISSING = [0x000C66D0, 0x000C6870, 0x000CD400, 0x000CEBC0, 0x000CF470,
           0x000CF840, 0x00105E00, 0x001EDE90, 0x001F1E90, 0x0021BE50]

here = Path(__file__).resolve().parent
work = here.parent.parent
gen = here.parent / 'project/src/recomp/gen'
python = work / 'recomp-python/Scripts/python.exe'
xbe = here.parent / 'game_files/default.xbe'
disasm, func_id, abi = sys.argv[1:4]

bodies = []
for a in MISSING:
    out = subprocess.run([str(python), '-m', 'tools.recomp', str(xbe), '-f', f'0x{a:X}',
                          '--game-name', 'FIFA Street', '--disasm-dir', disasm,
                          '--func-id-dir', func_id, '--abi-dir', abi],
                         cwd=work / 'xboxrecomp', capture_output=True, text=True, check=True).stdout
    m = re.search(rf'/\*\*\n \* sub_{a:08X}\n.*?\nvoid sub_{a:08X}\(void\)\n\{{.*?\n\}}\n', out, re.S)
    if not m:
        raise SystemExit(f'no translation for {a:08X}')
    bodies.append(m.group(0))
    print(f'translated sub_{a:08X}')

(gen / 'recomp_extra.c').write_text(
    '/* Functions reached only through code-built function pointers; see\n'
    ' * street1/hle/add-missing-functions.py. Generated by tools.recomp -f. */\n\n'
    '#define RECOMP_GENERATED_CODE\n#include "recomp_funcs.h"\n#include <math.h>\n\n'
    + '\n'.join(bodies), encoding='utf-8', newline='\n')

funcs = gen / 'recomp_funcs.h'
text = funcs.read_text(encoding='utf-8')
decls = ''.join(f'void sub_{a:08X}(void);\n' for a in MISSING if f'void sub_{a:08X}(void);' not in text)
if decls:
    anchor = re.search(r'^void sub_[0-9A-F]{8}\(void\);\n', text, re.M)
    text = text[:anchor.start()] + decls + text[anchor.start():]
    funcs.write_text(text, encoding='utf-8', newline='\n')

disp = gen / 'recomp_dispatch.c'
text = disp.read_text(encoding='utf-8')
for a in MISSING:
    entry = f'    {{ 0x{a:08X}u, (recomp_func_t)sub_{a:08X} }},\n'
    if entry in text:
        continue
    rows = list(re.finditer(r'^    \{ 0x([0-9A-F]{8})u, \(recomp_func_t\)\w+ \},\n', text, re.M))
    after = [r for r in rows if int(r.group(1), 16) > a][0]
    text = text[:after.start()] + entry + text[after.start():]
# The generator writes the row count as a literal; derive it from the table.
text = re.sub(r'static const size_t g_recomp_table_size = \d+;',
              'static const size_t g_recomp_table_size =\n'
              '    sizeof(g_recomp_table) / sizeof(g_recomp_table[0]);', text)
disp.write_text(text, encoding='utf-8', newline='\n')
print('added', len(MISSING), 'functions')
