/* Offline DXBC generator. Including the backend deliberately obtains exactly
 * the same concatenated HLSL and compile flags as runtime fallback. */
#define NV2A_GPU_SHADER_GENERATOR
#include "nv2a_gpu_compute.c"
int main(int argc, char **argv) {
  if (argc != 2) {
    fprintf(stderr, "usage: compile_gpu_shader output.inc\n");
    return 2;
  }
  ID3DBlob *code = NULL, *error = NULL;
  HRESULT hr = D3DCompile(
      source, sizeof(source) - 1, "nv2a_gpu_compute", NULL, NULL, "main",
      "cs_5_0", D3DCOMPILE_ENABLE_STRICTNESS | D3DCOMPILE_IEEE_STRICTNESS, 0,
      &code, &error);
  if (FAILED(hr)) {
    fprintf(stderr, "offline shader compile failed: %s\n",
            error ? (char *)ID3D10Blob_GetBufferPointer(error)
                  : "no diagnostic");
    RELEASE(error, ID3D10Blob);
    return 1;
  }
  RELEASE(error, ID3D10Blob);
  FILE *f = fopen(argv[1], "wb");
  if (!f) {
    RELEASE(code, ID3D10Blob);
    return 1;
  }
  const unsigned char *data = ID3D10Blob_GetBufferPointer(code);
  size_t bytes = ID3D10Blob_GetBufferSize(code);
  unsigned long long hash = shader_source_hash();
  fprintf(f, "/* Generated by compile_gpu_shader.c; never hand-edit. */\n");
  fprintf(f,
          "static const unsigned long long s_gpu_dxbc_source_hash = "
          "0x%016llXULL;\n",
          hash);
  fprintf(f, "static const unsigned char s_gpu_dxbc[] = {\n");
  for (size_t i = 0; i < bytes; i++) {
    if (!(i % 16))
      fputs("  ", f);
    fprintf(f, "0x%02X,", data[i]);
    fputc((i % 16 == 15 || i + 1 == bytes) ? '\n' : ' ', f);
  }
  fputs("};\n", f);
  int failed = ferror(f);
  failed |= fclose(f) != 0;
  printf("DXBC generated: %zu bytes, source FNV1a=%016llX\n", bytes, hash);
  RELEASE(code, ID3D10Blob);
  return failed ? 1 : 0;
}
